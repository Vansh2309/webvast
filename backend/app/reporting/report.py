"""Report generation.

Produces a self-contained HTML report (printable to PDF from the browser) and a
JSON export from a scan record. No external template files are needed.
"""
from __future__ import annotations

from typing import Any, Dict

from jinja2 import Environment, select_autoescape

_SEV_COLOR = {
    "critical": "#7f1d1d", "high": "#b91c1c", "medium": "#c2410c",
    "low": "#a16207", "info": "#1d4ed8",
}

_TEMPLATE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>WebVAST Report - {{ scan.target_url }}</title>
<style>
  body{font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;
       margin:0;color:#111827;background:#f9fafb}
  .wrap{max-width:960px;margin:0 auto;padding:32px}
  h1{font-size:22px;margin:0 0 4px} .sub{color:#6b7280;margin-bottom:24px}
  .cards{display:flex;gap:10px;flex-wrap:wrap;margin:16px 0 28px}
  .card{flex:1;min-width:110px;border-radius:10px;padding:14px;color:#fff;text-align:center}
  .card .n{font-size:26px;font-weight:700} .card .l{font-size:12px;text-transform:uppercase;opacity:.9}
  .meta{background:#fff;border:1px solid #e5e7eb;border-radius:10px;padding:16px;margin-bottom:24px;font-size:14px}
  .meta div{margin:2px 0}
  .finding{background:#fff;border:1px solid #e5e7eb;border-left-width:5px;border-radius:8px;
           padding:16px;margin-bottom:14px}
  .badge{display:inline-block;color:#fff;font-size:11px;font-weight:700;padding:2px 8px;
         border-radius:999px;text-transform:uppercase;letter-spacing:.03em}
  .ftitle{font-size:16px;font-weight:600;margin:8px 0 6px}
  .kv{font-size:13px;color:#374151;margin:4px 0}
  .kv b{color:#111827} code{background:#f3f4f6;padding:1px 5px;border-radius:4px;
       font-family:ui-monospace,Menlo,monospace;font-size:12px;word-break:break-all}
  .rem{background:#ecfdf5;border:1px solid #a7f3d0;border-radius:6px;padding:8px 10px;
       font-size:13px;margin-top:8px}
  footer{color:#9ca3af;font-size:12px;text-align:center;margin-top:28px}
  @media print{body{background:#fff}.card{-webkit-print-color-adjust:exact;print-color-adjust:exact}}
</style></head><body><div class="wrap">
  <h1>Web Application Vulnerability Report</h1>
  <div class="sub">Target: {{ scan.target_url }} &middot; Generated by WebVAST</div>

  <div class="cards">
  {% for sev in ['critical','high','medium','low','info'] %}
    <div class="card" style="background:{{ colors[sev] }}">
      <div class="n">{{ scan.severity_counts.get(sev, 0) }}</div>
      <div class="l">{{ sev }}</div>
    </div>
  {% endfor %}
  </div>

  <div class="meta">
    <div><b>Status:</b> {{ scan.status }}</div>
    <div><b>Scanned:</b> {{ scan.created_at }} &rarr; {{ scan.finished_at or '-' }}</div>
    <div><b>Modules:</b> {{ scan.modules | join(', ') }}</div>
    <div><b>Pages crawled:</b> {{ scan.pages_crawled }} &middot;
         <b>Requests sent:</b> {{ scan.requests_sent }} &middot;
         <b>Duration:</b> {{ scan.duration_s }}s</div>
    {% if scan.error %}<div style="color:#b91c1c"><b>Note:</b> {{ scan.error }}</div>{% endif %}
  </div>

  <h2>Findings ({{ scan.findings | length }})</h2>
  {% if not scan.findings %}<p>No vulnerabilities were detected by the selected modules.</p>{% endif %}
  {% for f in scan.findings %}
    <div class="finding" style="border-left-color:{{ colors[f.severity] }}">
      <span class="badge" style="background:{{ colors[f.severity] }}">{{ f.severity }}</span>
      <span class="badge" style="background:#6b7280">{{ f.confidence }}</span>
      {% if f.cwe %}<span class="badge" style="background:#374151">{{ f.cwe }}</span>{% endif %}
      <div class="ftitle">{{ f.title }}</div>
      <div class="kv"><b>URL:</b> <code>{{ f.url }}</code></div>
      {% if f.parameter %}<div class="kv"><b>Parameter:</b> <code>{{ f.parameter }}</code></div>{% endif %}
      {% if f.payload %}<div class="kv"><b>Payload:</b> <code>{{ f.payload }}</code></div>{% endif %}
      <div class="kv">{{ f.description }}</div>
      {% if f.evidence %}<div class="kv"><b>Evidence:</b> <code>{{ f.evidence }}</code></div>{% endif %}
      <div class="rem"><b>Remediation:</b> {{ f.remediation }}</div>
    </div>
  {% endfor %}

  <footer>WebVAST &middot; For use only against systems you own or are authorized to test.</footer>
</div></body></html>"""

_env = Environment(autoescape=select_autoescape(["html", "xml"]))
_tpl = _env.from_string(_TEMPLATE)


def render_html(scan: Dict[str, Any]) -> str:
    return _tpl.render(scan=scan, colors=_SEV_COLOR)
